from make_checklists import OUT, HEAD, CENTER, f, setup, cell, boxrange
from make_loto import title, note, section, heads, FOOT, NOTE


def info_rows(ws, r, labels, last="G"):
    for lb in labels:
        cell(ws, f"A{r}", lb, f(9, True), HEAD, CENTER)
        ws.merge_cells(f"B{r}:{last}{r}")
        cell(ws, f"B{r}", None); boxrange(ws, f"B{r}:{last}{r}")
        ws.row_dimensions[r].height = 22; r += 1
    return r


def check_table(ws, r, groups, n=1):
    """열: 번호 | 점검 내용 | 근거 | 양호 | 불량 | 해당없음 | 조치 내용"""
    for sec, items in groups:
        section(ws, r, "G", sec); r += 1
        heads(ws, r, "ABCDEFG", ["번호", "점검 내용", "근거", "양호", "불량", "해당없음", "조치 내용"]); r += 1
        for text, basis in items:
            cell(ws, f"A{r}", n, align=CENTER)
            cell(ws, f"B{r}", text, f(9))
            cell(ws, f"C{r}", basis, f(8), align=CENTER)
            for col in "DEFG":
                cell(ws, f"{col}{r}", None, align=CENTER)
            ws.row_dimensions[r].height = 30 if len(text) > 33 else 22
            n += 1; r += 1
        r += 1
    return r, n


def sign_row(ws, r, left="점검자", right="관리감독자"):
    cell(ws, f"A{r}", left, f(10, True), HEAD, CENTER)
    ws.merge_cells(f"B{r}:C{r}"); cell(ws, f"B{r}", None); boxrange(ws, f"B{r}:C{r}")
    ws.merge_cells(f"D{r}:E{r}"); cell(ws, f"D{r}", right, f(10, True), HEAD, CENTER); boxrange(ws, f"D{r}:E{r}")
    ws.merge_cells(f"F{r}:G{r}"); cell(ws, f"F{r}", None); boxrange(ws, f"F{r}:G{r}")
    ws.row_dimensions[r].height = 28
    return r + 1


def log_sheet(ws, name, sub, cols, widths, rows=16, marks=()):
    setup(ws, landscape=True)
    last = chr(ord("A") + len(cols) - 1)
    title(ws, last, name, sub)
    for i, (h, w) in enumerate(zip(cols, widths)):
        col = chr(ord("A") + i)
        ws.column_dimensions[col].width = w
        cell(ws, f"{col}4", h, f(9, True), HEAD, CENTER)
    ws.row_dimensions[4].height = 32
    for r in range(5, 5 + rows):
        for i, h in enumerate(cols):
            cell(ws, f"{chr(ord('A') + i)}{r}", "[ ]" if h in marks else None, align=CENTER)
        ws.row_dimensions[r].height = 24
    return 5 + rows + 1, last


