def guard_check(ws):
    setup(ws)
    for col, w in zip("ABCDEFG", [11, 50, 15, 5, 5, 8, 13]):
        ws.column_dimensions[col].width = w
    title(ws, "G", "기계 방호장치 점검표",
          "설비마다 정기적으로 점검합니다. 사업주는 방호장치가 정상 기능을 하도록 상시 점검·정비해야 합니다 (산업안전보건법 제80조제3항).")
    r = info_rows(ws, 4, ["점검 일자", "설비명·위치", "점검자"])
    r += 1
